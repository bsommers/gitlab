# ---------------------------------------------------------------------------
# Onboarding Breadcrumbs Helper (stderr-only so stdout pipes stay clean)
# ---------------------------------------------------------------------------
def print_next_steps(
    summary: str,
    steps: List[Tuple[str, str]],
    *,
    quiet: bool = False,
    json_mode: bool = False,
    stream: Any = sys.stderr,
) -> None:
    """Print completion summary and numbered next-step commands to stderr."""
    if quiet or json_mode:
        return
    if summary:
        print(summary, file=stream)
    print("\nNext steps:", file=stream)
    width = max((len(cmd) for cmd, _ in steps), default=24)
    for idx, (cmd, reason) in enumerate(steps, 1):
        print(f"  {idx}. {cmd:<{width}}  # {reason}", file=stream)


# ---------------------------------------------------------------------------
# Minimal fallback YAML parser in case PyYAML is not installed
# ---------------------------------------------------------------------------
def load_yaml_file(path: Path) -> Dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    if yaml is not None:
        return yaml.safe_load(text) or {}
    return _simple_yaml_parse(text)


def _simple_yaml_parse(text: str) -> Dict[str, Any]:
    root: Dict[str, Any] = {}
    stack: List[Tuple[int, Dict[str, Any]]] = [(-1, root)]
    for raw_line in text.splitlines():
        line = raw_line.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip(" "))
        stripped = line.strip()
        if ":" not in stripped:
            continue
        key, val = stripped.split(":", 1)
        key = key.strip()
        val = val.strip()
        while len(stack) > 1 and indent <= stack[-1][0]:
            stack.pop()
        current = stack[-1][1]
        if val == "":
            new_dict: Dict[str, Any] = {}
            current[key] = new_dict
            stack.append((indent, new_dict))
        else:
            if (val.startswith('"') and val.endswith('"')) or (
                val.startswith("'") and val.endswith("'")
            ):
                parsed_val: Any = val[1:-1]
            elif val.lower() in ("true", "false"):
                parsed_val = val.lower() == "true"
            elif val.isdigit():
                parsed_val = int(val)
            else:
                parsed_val = val
            current[key] = parsed_val
    return root


