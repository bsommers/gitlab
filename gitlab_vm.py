# Connection URL Discovery & Health Check
# ---------------------------------------------------------------------------
def discover_connection_details(
    spec: Dict[str, Any],
    provider: Optional[str] = None,
) -> Dict[str, Any]:
    active_provider = resolve_provider(spec, provider)
    vm_name = str(spec.get("vm", {}).get("name", "gitlab-server"))
    gitlab_cfg = spec.get("gitlab", {})
    pve_cfg = spec.get("proxmox", {})
    ext_proto = str(gitlab_cfg.get("external_protocol", "http"))
    ext_host = str(gitlab_cfg.get("external_host", "localhost"))
    ext_port = int(gitlab_cfg.get("external_port", 8080))
    ssh_port = int(gitlab_cfg.get("ssh_port", 2222))
    root_pw = str(gitlab_cfg.get("initial_root_password", "GitLabRoot!2026"))

    pve_node: Optional[str] = None
    pve_vmid: Optional[int] = None
    guest_ip: Optional[str] = None

    if active_provider == "proxmox":
        pve_node = str(pve_cfg.get("node", "pve"))
        existing = proxmox_find_existing_vm(spec)
        if existing:
            vm_state = str(existing.get("status", "unknown"))
            pve_vmid = int(existing.get("vmid", pve_cfg.get("vmid", 112)))
            guest_ip = proxmox_get_guest_ip(spec, pve_vmid)
        else:
            vm_state = "not_created"
            pve_vmid = int(pve_cfg.get("vmid", 112))
        if guest_ip and ext_host in ("localhost", "127.0.0.1", "auto", ""):
            ext_host = guest_ip
        ssh_port = int(pve_cfg.get("ssh_port", 22))
        ssh_target_host = guest_ip or ext_host
    else:
        vm_info = get_vm_info(vm_name)
        vm_state = vm_info.get("VMState", "not_created")
        # Inspect live NAT port-forwarding rules on the VM if it exists in VirtualBox
        for k, v in vm_info.items():
            if k.startswith("Forwarding("):
                parts = v.split(",")
                if len(parts) >= 6:
                    rule_name, _, _, hport, _, _ = parts[:6]
                    if rule_name == "http" and hport.isdigit():
                        ext_port = int(hport)
                    elif rule_name == "ssh" and hport.isdigit():
                        ssh_port = int(hport)
        ssh_target_host = "127.0.0.1"

    if (ext_proto == "http" and ext_port == 80) or (ext_proto == "https" and ext_port == 443):
        web_url = f"{ext_proto}://{ext_host}"
    else:
        web_url = f"{ext_proto}://{ext_host}:{ext_port}"

    if ssh_port == 22:
        git_ssh_url = f"git@{ext_host}:<namespace>/<project>.git"
    else:
        git_ssh_url = f"ssh://git@{ext_host}:{ssh_port}/<namespace>/<project>.git"

    # Probe HTTP health
    http_status: Optional[int] = None
    http_ready = False
    probe_url = f"{web_url}/users/sign_in"
    try:
        req = urllib.request.Request(probe_url, method="GET")
        with urllib.request.urlopen(req, timeout=3) as resp:
            http_status = resp.status
            http_ready = resp.status in (200, 302)
    except urllib.error.HTTPError as e:
        http_status = e.code
        http_ready = e.code in (200, 302)
    except Exception:
        http_ready = False

    result: Dict[str, Any] = {
        "provider": active_provider,
        "vm_name": vm_name,
        "vm_state": vm_state,
        "gitlab_web_url": web_url,
        "gitlab_sign_in_url": f"{web_url}/users/sign_in",
        "gitlab_git_ssh_url": git_ssh_url,
        "vm_ssh_command": (
            f"ssh -i {ROOT_DIR / str(spec.get('auth', {}).get('ssh_key_path', '.state/ssh/id_ed25519'))} "
            f"-p {ssh_port} {spec.get('auth', {}).get('ssh_user', 'ubuntu')}@{ssh_target_host}"
        ),
        "username": "root",
        "initial_root_password": root_pw,
        "http_ready": http_ready,
        "http_status": http_status,
    }
    if active_provider == "proxmox":
        result["proxmox_node"] = pve_node
        result["proxmox_vmid"] = pve_vmid
        result["guest_ip"] = guest_ip
    return result


def show_connection_url(
    spec: Dict[str, Any],
    as_json: bool = False,
    url_only: bool = False,
    provider: Optional[str] = None,
) -> None:
    details = discover_connection_details(spec, provider=provider)
    if as_json:
        print(json.dumps(details, indent=2))
        return
    if url_only:
        print(details["gitlab_web_url"])
        return

    status_badge = (
        "\033[1;32mONLINE (HTTP Ready)\033[0m"
        if details["http_ready"]
        else f"\033[1;33m{details['vm_state'].upper()} (HTTP status: {details['http_status'] or 'unreachable'})\033[0m"
    )
    provider_label = "PROXMOX VE" if details.get("provider") == "proxmox" else "VIRTUALBOX"
    print("\n" + "=" * 68)
    print(f"  GITLAB {provider_label} SERVER - CONNECTION DETAILS")
    print("=" * 68)
    if details.get("provider") == "proxmox":
        print(
            f"  VM Name / VMID   : {details['vm_name']} "
            f"(VMID {details.get('proxmox_vmid')} on node '{details.get('proxmox_node')}')"
        )
        if details.get("guest_ip"):
            print(f"  Guest IP         : {details['guest_ip']}")
    else:
        print(f"  VM Name          : {details['vm_name']}")
    print(f"  Status           : {status_badge}")
    print(f"  GitLab Web URL   : \033[1;36m{details['gitlab_web_url']}\033[0m")
    print(f"  Sign-In URL      : {details['gitlab_sign_in_url']}")
    print(f"  Git SSH Clone    : {details['gitlab_git_ssh_url']}")
    print("-" * 68)
    print(f"  Admin Username   : {details['username']}")
    print(f"  Initial Password : {details['initial_root_password']}")
    print(f"  Retrieve in VM   : sudo cat /etc/gitlab/initial_root_password")
    print("-" * 68)
    print(f"  VM SSH Access    : {details['vm_ssh_command']}")
    print("=" * 68 + "\n")


