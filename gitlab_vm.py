def cmd_init(
    target_path: Path,
    *,
    force: bool = False,
    quiet: bool = False,
) -> int:
    if target_path.exists() and not force:
        print(
            f"Configuration already exists at {target_path} (use --force to overwrite).",
            file=sys.stderr,
        )
        print_next_steps(
            "",
            [
                ("./gitlab_vm.py doctor", "verify VirtualBox, qemu-img, and host dependencies"),
                ("./gitlab_vm.py --dry-run up", "preview VM creation and GitLab provisioning commands"),
                ("./gitlab_vm.py up", "create the Linux VM, provision GitLab, and show URL"),
            ],
            quiet=quiet,
        )
        return 0

    target_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.write_text(STARTER_SPEC_YAML, encoding="utf-8")
    print_next_steps(
        f"Initialized declarative VM specification at {target_path}",
        [
            ("./gitlab_vm.py doctor", "verify VirtualBox, qemu-img, and host dependencies"),
            ("./gitlab_vm.py --dry-run up", "preview VM creation and GitLab provisioning commands"),
            ("./gitlab_vm.py up", "create the Linux VM, provision GitLab, and show URL"),
        ],
        quiet=quiet,
    )
    return 0


def cmd_doctor(
    spec_path: Path,
    *,
    as_json: bool = False,
    quiet: bool = False,
    cli_provider: Optional[str] = None,
) -> int:
    spec = load_yaml_file(spec_path) if spec_path.exists() else {}
    provider = resolve_provider(spec, cli_provider)
    vbox_required = provider == "virtualbox"
    proxmox_required = provider == "proxmox"

    checks: List[Dict[str, Any]] = []

    def add_check(name: str, required: bool, found_path: Optional[str], remedy: str) -> None:
        checks.append(
            {
                "name": name,
                "required": required,
                "ok": bool(found_path),
                "path": found_path or "",
                "remedy": "" if found_path else remedy,
            }
        )

    add_check(
        "VBoxManage",
        vbox_required,
        shutil.which("VBoxManage"),
        "Install Oracle VirtualBox 7.x+ (brew install --cask virtualbox or https://www.virtualbox.org/)",
    )
    add_check(
        "qemu-img",
        vbox_required,
        shutil.which("qemu-img"),
        "Install QEMU disk utility (macOS: brew install qemu | Ubuntu/Debian: sudo apt-get install -y qemu-utils)",
    )
    iso_tool = (
        shutil.which("hdiutil")
        or shutil.which("genisoimage")
        or shutil.which("mkisofs")
        or shutil.which("xorriso")
    )
    add_check(
        "iso-builder (hdiutil/genisoimage/mkisofs/xorriso)",
        vbox_required,
        iso_tool,
        "Install an ISO builder (Ubuntu/Debian: sudo apt-get install -y genisoimage xorriso)",
    )
    add_check("curl", True, shutil.which("curl"), "Install curl (sudo apt-get install -y curl)")
    add_check("ssh", True, shutil.which("ssh"), "Install OpenSSH client (sudo apt-get install -y openssh-client)")
    add_check(
        "ssh-keygen",
        True,
        shutil.which("ssh-keygen"),
        "Install OpenSSH keygen utility (sudo apt-get install -y openssh-client)",
    )
    add_check(
        "ansible-playbook (optional; falls back to SSH script)",
        False,
        shutil.which("ansible-playbook"),
        "Optional: pip install ansible-core (if omitted, gitlab_vm.py automatically uses scripts/install-gitlab.sh)",
    )
    add_check(
        f"spec ({spec_path})",
        True,
        str(spec_path) if spec_path.exists() else None,
        f"Run './gitlab_vm.py init -c {spec_path}' to generate a starter VM specification",
    )

    if proxmox_required or spec.get("proxmox"):
        pve_cfg = spec.get("proxmox", {})
        api_url = str(pve_cfg.get("api_url", "https://192.168.1.62:8006"))
        token = get_proxmox_token(spec)
        token_source = "configured (env or .state/proxmox/api_token)" if token else None
        add_check(
            "proxmox-api-token",
            proxmox_required,
            token_source,
            "Set PROXMOX_API_TOKEN='USER@REALM!TOKENID=UUID' or save token to .state/proxmox/api_token",
        )
        pve_info: Optional[str] = None
        if token:
            try:
                ver = proxmox_api_request(spec, "version", timeout=5)
                if isinstance(ver, dict) and ver.get("version"):
                    existing = proxmox_find_existing_vm(spec)
                    if existing:
                        pve_info = (
                            f"{api_url} (PVE {ver.get('version')}; existing VM "
                            f"'{existing['name']}' VMID {existing['vmid']} [{existing['status']}], "
                            f"protect_existing={bool(pve_cfg.get('protect_existing', True))})"
                        )
                    else:
                        pve_info = f"{api_url} (PVE {ver.get('version')})"
            except Exception:
                pve_info = None
        add_check(
            f"proxmox-api ({api_url})",
            proxmox_required,
            pve_info,
            f"Verify Proxmox VE reachability at {api_url} and API token permissions",
        )

    all_required_ok = all(c["ok"] for c in checks if c["required"])

    if as_json:
        print(json.dumps({"ok": all_required_ok, "provider": provider, "checks": checks}, indent=2))
        return 0 if all_required_ok else 1

    print(f"\nGitLab IaC ({provider}) — Environment Preflight (doctor)")
    print("=" * 64)
    for c in checks:
        if c["ok"]:
            badge = "\033[1;32m[OK]\033[0m  "
            detail = c["path"]
        elif c["required"]:
            badge = "\033[1;31m[MISS]\033[0m"
            detail = f"Missing -> {c['remedy']}"
        else:
            badge = "\033[1;33m[OPT]\033[0m "
            detail = f"Not configured/installed -> {c['remedy']}"
        print(f"  {badge} {c['name']}: {detail}")
    print("=" * 64)

    if not all_required_ok:
        print(
            "\nerror: one or more required dependencies are missing. Apply the remedies above and re-run './gitlab_vm.py doctor'.",
            file=sys.stderr,
        )
        return 1

    print_next_steps(
        "Environment verified: all required tools and specifications are ready.",
        [
            ("./gitlab_vm.py --dry-run up", "preview all VM and provisioning commands"),
            ("./gitlab_vm.py up", "verify/create the Linux VM, ensure GitLab CE is ready, and show URL"),
            ("./gitlab_vm.py url", "inspect VM status and GitLab connection URL"),
        ],
        quiet=quiet,
    )
    return 0


