def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="gitlab_vm.py",
        description="Standalone IaC & Proxmox VE / VirtualBox CLI Manager for GitLab Server",
        epilog=WORKFLOW_EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"%(prog)s {__version__}",
    )
    parser.add_argument(
        "-c",
        "--config",
        type=Path,
        default=DEFAULT_SPEC_PATH,
        help=f"Path to declarative VM spec YAML (default: {DEFAULT_SPEC_PATH})",
    )
    parser.add_argument(
        "--provider",
        choices=["auto", "proxmox", "virtualbox"],
        default=None,
        help="Hypervisor provider override (default: from iac/vm-spec.yaml vm.provider)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print Proxmox/VBoxManage/provisioning commands without executing them",
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Print executed shell commands",
    )
    parser.add_argument(
        "-q",
        "--quiet",
        action="store_true",
        help="Suppress informational logs and Next steps hints",
    )

    sub = parser.add_subparsers(dest="command", required=True)

    # init
    p_init = sub.add_parser("init", help="Initialize starter iac/vm-spec.yaml configuration")
    p_init.add_argument("--force", action="store_true", help="Overwrite existing spec file")
    p_init.add_argument(
        "--non-interactive",
        "--yes",
        action="store_true",
        help="Run non-interactively without prompts",
    )

    # doctor
    p_doc = sub.add_parser("doctor", help="Verify Proxmox/VirtualBox and host dependencies")
    p_doc.add_argument("--json", action="store_true", help="Output preflight report as JSON")

    # guide
    sub.add_parser("guide", help="Print the built-in step-by-step workflow and lifecycle guide")

    # up
    p_up = sub.add_parser("up", help="Create Linux VM (without overwriting existing VM), provision GitLab, and show URL")
    p_up.add_argument(
        "--provisioner",
        choices=["auto", "ansible", "ssh"],
        default="auto",
        help="Provisioning engine to use inside the VM (default: auto)",
    )
    p_up.add_argument(
        "--force-provision",
        action="store_true",
        help="Re-run GitLab provisioning even if an existing Proxmox VM already responds on HTTP",
    )

    # create-vm
    p_create = sub.add_parser("create-vm", help="Create and boot the Linux VM (never overwrites an existing VM)")
    p_create.add_argument("--no-start", action="store_true", help="Create VM without starting it")

    # provision
    p_prov = sub.add_parser("provision", help="Provision GitLab server inside the running Linux VM")
    p_prov.add_argument(
        "--provisioner",
        choices=["auto", "ansible", "ssh"],
        default="auto",
        help="Provisioning engine to use (default: auto)",
    )

    # url / status
    p_url = sub.add_parser("url", aliases=["status", "info"], help="Show GitLab connection URL and status")
    p_url.add_argument("--json", action="store_true", help="Output connection details as JSON")
    p_url.add_argument("--raw", action="store_true", help="Print only the GitLab HTTP URL")

    # ssh
    sub.add_parser("ssh", help="Open an interactive SSH shell into the Linux VM")

    # start / stop / destroy
    sub.add_parser("start", help="Start the Linux VM in headless mode")
    sub.add_parser("stop", help="Gracefully shut down the Linux VM")
    p_destroy = sub.add_parser("destroy", help="Power off and delete the VM (refuses if proxmox.protect_existing=true)")
    p_destroy.add_argument(
        "--force",
        action="store_true",
        help="Override proxmox.protect_existing guard when destroying a VM",
    )

    return parser


def main(argv: Optional[List[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.command == "init":
        return cmd_init(args.config, force=args.force, quiet=args.quiet)
    if args.command == "doctor":
        return cmd_doctor(
            args.config,
            as_json=args.json,
            quiet=args.quiet,
            cli_provider=args.provider,
        )
    if args.command == "guide":
        return cmd_guide()

    if not args.config.exists():
        print(f"error: specification file not found at {args.config}", file=sys.stderr)
        print(
            f"hint:  run './gitlab_vm.py init -c {args.config}' to bootstrap a workspace, or pass '--config PATH'.",
            file=sys.stderr,
        )
        return 1

    spec = load_yaml_file(args.config)
    runner = Runner(dry_run=args.dry_run, verbose=args.verbose, quiet=args.quiet)
    vm_name = str(spec.get("vm", {}).get("name", "gitlab-server"))
    active_provider = resolve_provider(spec, args.provider)

    try:
        if args.command == "create-vm":
            create_vm(runner, spec, start=not args.no_start, provider=active_provider)
            print_next_steps(
                "",
                [
                    ("./gitlab_vm.py provision", "install and configure GitLab CE inside the running VM"),
                    ("./gitlab_vm.py url", "display the GitLab connection URL and credentials"),
                    ("./gitlab_vm.py ssh", "open an interactive SSH session into the VM"),
                ],
                quiet=args.quiet,
            )
        elif args.command == "provision":
            provision_gitlab(runner, spec, provisioner=args.provisioner, provider=active_provider)
            print_next_steps(
                "",
                [
                    ("./gitlab_vm.py url", "display the GitLab connection URL and credentials"),
                    ("./gitlab_vm.py url --raw", "print only the GitLab Web URL"),
                    ("./gitlab_vm.py ssh", "inspect the VM via interactive SSH"),
                ],
                quiet=args.quiet,
            )
        elif args.command in ("url", "status", "info"):
            show_connection_url(spec, as_json=args.json, url_only=args.raw, provider=active_provider)
        elif args.command == "up":
            create_vm(runner, spec, start=True, provider=active_provider)
            protect_existing = bool(spec.get("proxmox", {}).get("protect_existing", True))
            if active_provider == "proxmox" and protect_existing and not args.force_provision:
                details = discover_connection_details(spec, provider=active_provider)
                if details.get("http_ready"):
                    runner.success(
                        f"GitLab is already provisioned and online at {details['gitlab_web_url']} "
                        f"on existing Proxmox VM '{vm_name}' (VMID {details.get('proxmox_vmid')}). "
                        f"Skipping provisioning to preserve existing VM (pass --force-provision to re-run)."
                    )
                else:
                    provision_gitlab(runner, spec, provisioner=args.provisioner, provider=active_provider)
            else:
                provision_gitlab(runner, spec, provisioner=args.provisioner, provider=active_provider)
            show_connection_url(spec, provider=active_provider)
            print_next_steps(
                "",
                [
                    ("./gitlab_vm.py url", "re-check GitLab HTTP readiness and credentials"),
                    ("./gitlab_vm.py ssh", "open an interactive SSH session into the VM"),
                    ("./gitlab_vm.py stop", "gracefully shut down the VM when finished"),
                ],
                quiet=args.quiet,
            )
        elif args.command == "ssh":
            host, port, user, key_path = get_ssh_connection_params(spec, provider=active_provider)
            ssh_cmd = [
                "ssh",
                "-i",
                str(key_path),
                "-p",
                str(port),
                "-o",
                "StrictHostKeyChecking=no",
                "-o",
                "UserKnownHostsFile=/dev/null",
                f"{user}@{host}",
            ]
            if runner.dry_run:
                runner.run(ssh_cmd)
                return 0
            return subprocess.call(ssh_cmd)
        elif args.command == "start":
            if active_provider == "proxmox":
                pve_cfg = spec.get("proxmox", {})
                node = str(pve_cfg.get("node", "pve"))
                existing = proxmox_find_existing_vm(spec)
                vmid = existing["vmid"] if existing else int(pve_cfg.get("vmid", 112))
                if runner.dry_run:
                    runner.info(f"[dry-run] POST /nodes/{node}/qemu/{vmid}/status/start")
                else:
                    proxmox_api_request(spec, f"nodes/{node}/qemu/{vmid}/status/start", method="POST")
            else:
                runner.run(["VBoxManage", "startvm", vm_name, "--type", "headless"])
            print_next_steps(
                f"Started VM '{vm_name}'.",
                [("./gitlab_vm.py url", "check GitLab HTTP readiness and URL")],
                quiet=args.quiet,
            )
        elif args.command == "stop":
            if active_provider == "proxmox":
                pve_cfg = spec.get("proxmox", {})
                node = str(pve_cfg.get("node", "pve"))
                existing = proxmox_find_existing_vm(spec)
                vmid = existing["vmid"] if existing else int(pve_cfg.get("vmid", 112))
                if runner.dry_run:
                    runner.info(f"[dry-run] POST /nodes/{node}/qemu/{vmid}/status/shutdown")
                else:
                    proxmox_api_request(spec, f"nodes/{node}/qemu/{vmid}/status/shutdown", method="POST")
            else:
                runner.run(["VBoxManage", "controlvm", vm_name, "acpipowerbutton"])
            print_next_steps(
                f"Sent ACPI shutdown signal to VM '{vm_name}'.",
                [("./gitlab_vm.py start", "restart the VM in headless mode")],
                quiet=args.quiet,
            )
        elif args.command == "destroy":
            if active_provider == "proxmox":
                pve_cfg = spec.get("proxmox", {})
                protect_existing = bool(pve_cfg.get("protect_existing", True))
                existing = proxmox_find_existing_vm(spec)
                vmid = existing["vmid"] if existing else int(pve_cfg.get("vmid", 112))
                node = str(pve_cfg.get("node", "pve"))
                if protect_existing and not getattr(args, "force", False):
                    raise RuntimeError(
                        f"Refusing to destroy protected Proxmox VM '{vm_name}' (VMID {vmid} on node '{node}') "
                        f"because proxmox.protect_existing=true. Pass 'destroy --force' to override."
                    )
                if runner.dry_run:
                    runner.info(f"[dry-run] POST /nodes/{node}/qemu/{vmid}/status/stop")
                    runner.info(f"[dry-run] DELETE /nodes/{node}/qemu/{vmid}")
                elif existing:
                    if existing.get("status") == "running":
                        proxmox_api_request(spec, f"nodes/{node}/qemu/{vmid}/status/stop", method="POST")
                        time.sleep(2)
                    proxmox_api_request(spec, f"nodes/{node}/qemu/{vmid}", method="DELETE")
                    runner.success(f"Proxmox VM '{vm_name}' (VMID {vmid}) destroyed.")
                else:
                    runner.info(f"Proxmox VM '{vm_name}' (VMID {vmid}) does not exist.")
            else:
                if runner.dry_run or vm_exists(vm_name):
                    state = get_vm_state(vm_name) if not runner.dry_run else "running"
                    if state == "running":
                        runner.run(["VBoxManage", "controlvm", vm_name, "poweroff"], check=False)
                        time.sleep(2)
                    runner.run(["VBoxManage", "unregistervm", vm_name, "--delete-all"])
                    runner.success(f"VM '{vm_name}' destroyed.")
                else:
                    runner.info(f"VM '{vm_name}' does not exist.")
    except Exception as exc:
        runner.error(str(exc))
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
