def get_proxmox_token(spec: Dict[str, Any]) -> str:
    pve_cfg = spec.get("proxmox", {})
    env_var = str(pve_cfg.get("api_token_env", "PROXMOX_API_TOKEN"))
    token = (
        os.environ.get(env_var, "")
        or os.environ.get("PROXMOX_API_TOKEN", "")
        or os.environ.get("CVM_PROXMOX_TOKEN", "")
        or str(pve_cfg.get("api_token", ""))
    ).strip()
    if not token:
        token_file_rel = str(pve_cfg.get("api_token_file", ".state/proxmox/api_token"))
        token_file = (ROOT_DIR / token_file_rel).resolve()
        if token_file.exists():
            token = token_file.read_text(encoding="utf-8").strip()
    if token.startswith("PVEAPIToken="):
        token = token[len("PVEAPIToken=") :].strip()
    return token


def resolve_provider(spec: Dict[str, Any], cli_provider: Optional[str] = None) -> str:
    candidate = (
        cli_provider
        or os.environ.get("GITLAB_VM_PROVIDER")
        or str(spec.get("vm", {}).get("provider", "auto"))
    ).strip().lower()
    if candidate in ("proxmox", "virtualbox"):
        return candidate
    if spec.get("proxmox") and get_proxmox_token(spec):
        return "proxmox"
    return "virtualbox"


def proxmox_api_request(
    spec: Dict[str, Any],
    path: str,
    *,
    method: str = "GET",
    data: Optional[Dict[str, Any]] = None,
    timeout: int = 10,
) -> Any:
    pve_cfg = spec.get("proxmox", {})
    api_url = str(pve_cfg.get("api_url", "https://192.168.1.62:8006")).rstrip("/")
    if not api_url.endswith("/api2/json"):
        api_url = f"{api_url}/api2/json"

    token = get_proxmox_token(spec)
    if not token:
        raise RuntimeError(
            "Proxmox API token not configured. Set PROXMOX_API_TOKEN or write token to .state/proxmox/api_token."
        )

    url = f"{api_url}/{path.lstrip('/')}"
    encoded = urllib.parse.urlencode(data).encode("utf-8") if data else None
    headers = {
        "Authorization": f"PVEAPIToken={token}",
    }
    if encoded is not None:
        headers["Content-Type"] = "application/x-www-form-urlencoded"

    ctx = ssl.create_default_context()
    if bool(pve_cfg.get("insecure_tls", True)):
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE

    req = urllib.request.Request(url, data=encoded, headers=headers, method=method)
    with urllib.request.urlopen(req, context=ctx, timeout=timeout) as resp:
        payload = json.loads(resp.read().decode("utf-8"))
        return payload.get("data")


def proxmox_find_existing_vm(spec: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """
    Inspect Proxmox VE node VMs and detect any existing VM matching EITHER
    vm.name (e.g. 'gitlab-server') OR proxmox.vmid (e.g. 112).
    Never overwrites an existing VM on Proxmox.
    """
    vm_name = str(spec.get("vm", {}).get("name", "gitlab-server")).strip()
    pve_cfg = spec.get("proxmox", {})
    node = str(pve_cfg.get("node", "pve")).strip()
    target_vmid = int(pve_cfg.get("vmid", 112))

    if not get_proxmox_token(spec):
        return None

    try:
        vms = proxmox_api_request(spec, f"nodes/{node}/qemu", timeout=6)
        if isinstance(vms, list):
            by_name: Optional[Dict[str, Any]] = None
            by_vmid: Optional[Dict[str, Any]] = None
            for item in vms:
                if not isinstance(item, dict):
                    continue
                item_vmid = int(item.get("vmid", -1))
                item_name = str(item.get("name", "")).strip()
                if item_name == vm_name and item_vmid == target_vmid:
                    return {
                        "vmid": item_vmid,
                        "name": item_name,
                        "status": str(item.get("status", "unknown")),
                        "node": node,
                        "match": "name_and_vmid",
                    }
                if item_name == vm_name and by_name is None:
                    by_name = {
                        "vmid": item_vmid,
                        "name": item_name,
                        "status": str(item.get("status", "unknown")),
                        "node": node,
                        "match": "name",
                    }
                if item_vmid == target_vmid and by_vmid is None:
                    by_vmid = {
                        "vmid": item_vmid,
                        "name": item_name,
                        "status": str(item.get("status", "unknown")),
                        "node": node,
                        "match": "vmid",
                    }
            if by_name is not None:
                return by_name
            if by_vmid is not None:
                return by_vmid
    except Exception:
        pass

    try:
        st = proxmox_api_request(spec, f"nodes/{node}/qemu/{target_vmid}/status/current", timeout=5)
        if isinstance(st, dict) and st.get("status"):
            return {
                "vmid": target_vmid,
                "name": str(st.get("name", vm_name)),
                "status": str(st.get("status", "unknown")),
                "node": node,
                "match": "vmid",
            }
    except Exception:
        pass

    return None


def proxmox_get_guest_ip(spec: Dict[str, Any], vmid: Optional[int] = None) -> Optional[str]:
    pve_cfg = spec.get("proxmox", {})
    node = str(pve_cfg.get("node", "pve")).strip()
    resolved_vmid = int(vmid if vmid is not None else pve_cfg.get("vmid", 112))

    if not get_proxmox_token(spec):
        return None

    try:
        agent_data = proxmox_api_request(
            spec,
            f"nodes/{node}/qemu/{resolved_vmid}/agent/network-get-interfaces",
            timeout=5,
        )
        interfaces = agent_data.get("result", []) if isinstance(agent_data, dict) else []
        for iface in interfaces:
            if not isinstance(iface, dict):
                continue
            for addr in iface.get("ip-addresses", []):
                if not isinstance(addr, dict):
                    continue
                ip = str(addr.get("ip-address", "")).strip()
                if addr.get("ip-address-type") == "ipv4" and ip and not ip.startswith("127."):
                    return ip
    except Exception:
        pass

    try:
        cfg = proxmox_api_request(spec, f"nodes/{node}/qemu/{resolved_vmid}/config", timeout=5)
        if isinstance(cfg, dict):
            ipcfg = str(cfg.get("ipconfig0", ""))
            m = re.search(r"ip=([0-9]+\.[0-9]+\.[0-9]+\.[0-9]+)", ipcfg)
            if m:
                return m.group(1)
    except Exception:
        pass

    return None


def proxmox_wait_task(spec: Dict[str, Any], node: str, upid: str, timeout_sec: int = 300) -> None:
    deadline = time.time() + timeout_sec
    while time.time() < deadline:
        st = proxmox_api_request(spec, f"nodes/{node}/tasks/{urllib.parse.quote(upid, safe='')}/status")
        if isinstance(st, dict) and st.get("status") == "stopped":
            if st.get("exitstatus") != "OK":
                raise RuntimeError(f"Proxmox task {upid} failed: {st}")
            return
        time.sleep(2)
    raise TimeoutError(f"Timed out waiting for Proxmox task {upid}")


def create_vm_proxmox(runner: Runner, spec: Dict[str, Any], start: bool = True) -> None:
    vm_cfg = spec.get("vm", {})
    pve_cfg = spec.get("proxmox", {})
    auth_cfg = spec.get("auth", {})

    vm_name = str(vm_cfg.get("name", "gitlab-server")).strip()
    cpus = int(vm_cfg.get("cpus", 4))
    memory_mb = int(vm_cfg.get("memory_mb", 8192))
    disk_size_gb = int(vm_cfg.get("disk_size_gb", 40))

    node = str(pve_cfg.get("node", "pve")).strip()
    target_vmid = int(pve_cfg.get("vmid", 112))
    template_vmid = int(pve_cfg.get("template_vmid", 9000))
    bridge = str(pve_cfg.get("bridge", "vmbr0")).strip()

    # 1. Strict Non-Overwrite Guard: check if VM already exists on Proxmox (by name OR vmid)
    existing = proxmox_find_existing_vm(spec)
    if existing is not None:
        if existing["name"] != vm_name:
            raise RuntimeError(
                f"Refusing to overwrite existing Proxmox VMID {existing['vmid']} on node '{node}' "
                f"(currently occupied by VM '{existing['name']}', expected '{vm_name}')."
            )
        runner.info(
            f"Existing Proxmox VM '{existing['name']}' (VMID {existing['vmid']} on node '{node}', "
            f"state: {existing['status']}) detected — refusing to overwrite existing VM."
        )
        if start and existing["status"] != "running":
            if runner.dry_run:
                runner.info(
                    f"[dry-run] Would start existing Proxmox VM '{existing['name']}' (VMID {existing['vmid']}) "
                    f"via POST /nodes/{node}/qemu/{existing['vmid']}/status/start"
                )
            else:
                runner.info(f"Starting existing Proxmox VM '{existing['name']}' (VMID {existing['vmid']})...")
                proxmox_api_request(
                    spec,
                    f"nodes/{node}/qemu/{existing['vmid']}/status/start",
                    method="POST",
                )
        return

    ssh_key_rel = str(auth_cfg.get("ssh_key_path", ".state/ssh/id_ed25519"))
    ssh_key_path = (ROOT_DIR / ssh_key_rel).resolve()
    _, ssh_pub_key = ensure_ssh_keypair(runner, ssh_key_path)
    ssh_user = str(auth_cfg.get("ssh_user", "ubuntu"))

    if runner.dry_run:
        runner.info(
            f"[dry-run] Proxmox preflight: verified no existing VM named '{vm_name}' or VMID {target_vmid} on node '{node}'"
        )
        runner.info(
            f"[dry-run] POST /nodes/{node}/qemu/{template_vmid}/clone (newid={target_vmid}, name={vm_name}, full=1)"
        )
        runner.info(
            f"[dry-run] PUT /nodes/{node}/qemu/{target_vmid}/resize (disk=scsi0, size={disk_size_gb}G)"
        )
        runner.info(
            f"[dry-run] POST /nodes/{node}/qemu/{target_vmid}/config "
            f"(cores={cpus}, memory={memory_mb}, net0=virtio,bridge={bridge}, ciuser={ssh_user})"
        )
        if start:
            runner.info(f"[dry-run] POST /nodes/{node}/qemu/{target_vmid}/status/start")
        return

    runner.info(f"Cloning Proxmox template {template_vmid} -> VMID {target_vmid} ('{vm_name}') on node '{node}'...")
    upid = proxmox_api_request(
        spec,
        f"nodes/{node}/qemu/{template_vmid}/clone",
        method="POST",
        data={"newid": target_vmid, "name": vm_name, "full": 1},
    )
    if isinstance(upid, str) and upid:
        proxmox_wait_task(spec, node, upid)

    runner.info(f"Resizing Proxmox VMID {target_vmid} disk scsi0 to {disk_size_gb}G...")
    upid_resize = proxmox_api_request(
        spec,
        f"nodes/{node}/qemu/{target_vmid}/resize",
        method="PUT",
        data={"disk": "scsi0", "size": f"{disk_size_gb}G"},
    )
    if isinstance(upid_resize, str) and upid_resize:
        proxmox_wait_task(spec, node, upid_resize)

    runner.info(f"Configuring Proxmox VMID {target_vmid} Cloud-Init and hardware ({cpus} cores, {memory_mb} MB RAM)...")
    proxmox_api_request(
        spec,
        f"nodes/{node}/qemu/{target_vmid}/config",
        method="POST",
        data={
            "cores": cpus,
            "memory": memory_mb,
            "ciuser": ssh_user,
            "sshkeys": urllib.parse.quote(ssh_pub_key, safe=""),
            "ipconfig0": "ip=dhcp",
            "agent": "enabled=1",
        },
    )

    if start:
        runner.info(f"Starting Proxmox VM '{vm_name}' (VMID {target_vmid})...")
        proxmox_api_request(spec, f"nodes/{node}/qemu/{target_vmid}/status/start", method="POST")
        runner.success(f"Proxmox VM '{vm_name}' (VMID {target_vmid}) is now booting.")


