class Runner:
    def __init__(self, dry_run: bool = False, verbose: bool = False, quiet: bool = False) -> None:
        self.dry_run = dry_run
        self.verbose = verbose
        self.quiet = quiet

    def info(self, msg: str) -> None:
        if not self.quiet:
            print(f"\033[1;34m[INFO]\033[0m {msg}")

    def success(self, msg: str) -> None:
        if not self.quiet:
            print(f"\033[1;32m[OK]\033[0m   {msg}")

    def warn(self, msg: str) -> None:
        if not self.quiet:
            print(f"\033[1;33m[WARN]\033[0m {msg}", file=sys.stderr)

    def error(self, msg: str) -> None:
        print(f"\033[1;31m[ERR]\033[0m  {msg}", file=sys.stderr)

    def run(
        self,
        cmd: List[str],
        *,
        check: bool = True,
        capture: bool = False,
        cwd: Optional[Path] = None,
        env: Optional[Dict[str, str]] = None,
    ) -> subprocess.CompletedProcess[str]:
        cmd_str = " ".join(shlex.quote(str(c)) for c in cmd)
        if (self.dry_run or self.verbose) and not self.quiet:
            print(f"\033[0;36m  $ {cmd_str}\033[0m")
        if self.dry_run:
            return subprocess.CompletedProcess(cmd, 0, stdout="", stderr="")
        return subprocess.run(
            cmd,
            check=check,
            text=True,
            capture_output=capture,
            cwd=str(cwd) if cwd else None,
            env=env,
        )


